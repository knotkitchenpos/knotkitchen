/*
 * Builds public/offline.html: the page the Android app shows when the POS
 * cannot be loaded at all (capacitor.config.ts errorPath).
 *
 * It must work with NO network, so everything is inside the file: the logo
 * and the Geist font as data: URLs. A relative "icons/icon-192.png" was asked
 * of business.knotkitchen.com and came out as a broken image, and the
 * device's own font (a handwriting theme on some tablets) was used for text.
 *
 *   node scripts/build-offline-page.cjs
 *
 * Changing offline.html rebuilds the app (build-android-apk.yml).
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const b64 = (rel) => fs.readFileSync(path.join(root, rel)).toString("base64");
const logo = b64("public/icons/icon-192.png");
const font = b64("src/assets/fonts/geist-latin.woff2");
const APP = "https://business.knotkitchen.com";

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
<meta name="color-scheme" content="dark" />
<title>KnotKitchen POS - offline</title>
<!-- Generated by scripts/build-offline-page.cjs: edit that, not this file. -->
<style>
  @font-face {
    font-family: "KK";
    src: url(data:font/woff2;base64,${font}) format("woff2");
    font-weight: 400 700;
    font-display: block;
  }
  * { box-sizing: border-box; }
  html, body { height: 100%; margin: 0; }
  body {
    display: flex; align-items: center; justify-content: center;
    padding: max(24px, env(safe-area-inset-top)) 20px max(24px, env(safe-area-inset-bottom));
    background: radial-gradient(120% 80% at 50% 0%, #13213F 0%, #080F1F 60%);
    color: #F5F7FA; font-family: "KK", Roboto, Arial, sans-serif;
    -webkit-font-smoothing: antialiased;
  }
  main { width: 100%; max-width: 380px; text-align: center; }
  .logo {
    width: 76px; height: 76px; border-radius: 20px; display: block; margin: 0 auto;
    box-shadow: 0 10px 30px rgba(0, 0, 0, 0.45);
  }
  .badge {
    display: inline-flex; align-items: center; gap: 8px; margin-top: 26px;
    padding: 6px 12px; border-radius: 999px; font-size: 12.5px; font-weight: 600;
    background: rgba(253, 83, 2, 0.12); color: #FF8A4C; border: 1px solid rgba(253, 83, 2, 0.35);
  }
  .dot { width: 8px; height: 8px; border-radius: 50%; background: #FD5302; animation: pulse 1.6s ease-in-out infinite; }
  .badge.ok { background: rgba(34, 197, 94, 0.12); color: #4ADE80; border-color: rgba(34, 197, 94, 0.35); }
  .badge.ok .dot { background: #22C55E; animation: none; }
  @keyframes pulse { 0%, 100% { opacity: 1; transform: scale(1); } 50% { opacity: 0.35; transform: scale(0.75); } }
  h1 { font-size: 24px; font-weight: 700; letter-spacing: -0.01em; margin: 16px 0 8px; }
  p { font-size: 15px; line-height: 1.55; color: #A9B2C6; margin: 0 auto; max-width: 320px; }
  button {
    margin-top: 28px; width: 100%; max-width: 280px; height: 52px; border: 0; border-radius: 14px;
    background: #FD5302; color: #fff; font: 700 16px "KK", Roboto, Arial, sans-serif;
    box-shadow: 0 8px 22px rgba(253, 83, 2, 0.35); cursor: pointer;
  }
  button:active { transform: translateY(1px); background: #E04A02; }
  button:disabled { opacity: 0.7; }
  .tips { margin: 28px auto 0; padding: 14px 16px; max-width: 320px; text-align: left; list-style: none;
    border-radius: 14px; background: rgba(255, 255, 255, 0.04); border: 1px solid rgba(255, 255, 255, 0.07); }
  .tips li { font-size: 13px; line-height: 1.5; color: #8E98AE; padding-left: 18px; position: relative; }
  .tips li + li { margin-top: 6px; }
  .tips li::before { content: ""; position: absolute; left: 4px; top: 8px; width: 5px; height: 5px; border-radius: 50%; background: #FD5302; }
</style>
</head>
<body>
  <main>
    <img class="logo" src="data:image/png;base64,${logo}" alt="KnotKitchen" />
    <div class="badge" id="status" role="status"><span class="dot"></span><span id="status-text">Waiting for a connection…</span></div>
    <h1>You're offline</h1>
    <p>KnotKitchen POS can't reach the internet right now. It will reconnect on its own as soon as the connection is back.</p>
    <button type="button" id="retry">Try again</button>
    <ul class="tips">
      <li>Check that Wi-Fi or mobile data is on.</li>
      <li>Wi-Fi connected but no internet? Restart the router.</li>
      <li>A till opened online since its last update also opens offline: tap Try again.</li>
    </ul>
  </main>
<script>
  var APP = ${JSON.stringify(APP)};
  var statusEl = document.getElementById("status");
  var statusText = document.getElementById("status-text");
  var retry = document.getElementById("retry");
  var opening = false;

  function open() {
    if (opening) return;
    opening = true;
    retry.disabled = true;
    retry.textContent = "Opening…";
    // The POS, or its copy stored on this device (the service worker answers offline).
    location.replace(APP + "/");
    setTimeout(function () { opening = false; retry.disabled = false; retry.textContent = "Try again"; }, 8000);
  }

  // Is the server reachable? /api is never answered from the stored copy, so
  // any answer at all (even "sign in first") means the internet is back.
  function check() {
    if (opening) return;
    var done = false;
    var timer = setTimeout(function () { done = true; }, 5000);
    fetch(APP + "/api/user", { cache: "no-store", credentials: "omit", mode: "no-cors" })
      .then(function () {
        if (done) return;
        clearTimeout(timer);
        statusEl.className = "badge ok";
        statusText.textContent = "Back online. Opening…";
        setTimeout(open, 400);
      })
      .catch(function () { clearTimeout(timer); });
  }

  retry.addEventListener("click", open);
  window.addEventListener("online", check);
  setInterval(check, 5000);
  check();
</script>
</body>
</html>
`;

fs.writeFileSync(path.join(root, "public", "offline.html"), html);
console.log(`public/offline.html written (${Math.round(html.length / 1024)} KB)`);
