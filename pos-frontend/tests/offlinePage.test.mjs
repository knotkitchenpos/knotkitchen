import test from "node:test";
import assert from "node:assert";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// The app's offline page (capacitor errorPath), redesigned (owner, 2026-10-30):
// the logo was a broken image and the text took the device's handwriting font.

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const page = fs.readFileSync(path.join(__dirname, "..", "public", "offline.html"), "utf8");

test("the offline page needs nothing from the network: logo and font are inside it", () => {
  assert.match(page, /<img class="logo" src="data:image\/png;base64,/);
  assert.match(page, /src: url\(data:font\/woff2;base64,/);
  assert.doesNotMatch(page, /src="icons\//, "no relative image the offline app cannot load");
  assert.match(page, /font-family: "KK", Roboto, Arial, sans-serif;/);
});

test("it reconnects on its own, and Try again opens the POS (or its stored copy)", () => {
  assert.match(page, /var APP = "https:\/\/business\.knotkitchen\.com";/);
  assert.match(page, /fetch\(APP \+ "\/api\/user", \{ cache: "no-store", credentials: "omit", mode: "no-cors" \}\)/);
  assert.match(page, /setInterval\(check, 5000\);/);
  assert.match(page, /window\.addEventListener\("online", check\);/);
  assert.match(page, /location\.replace\(APP \+ "\/"\);/);
  assert.match(page, /Generated by scripts\/build-offline-page\.cjs/);
});
